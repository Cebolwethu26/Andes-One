import { Transaction, Wallet } from '../types';

interface StatementData {
  monthName: string;
  year: number;
  clientName: string;
  accountNumber: string;
  openingBalance: string;
  closingBalance: string;
  totalCredits: string;
  totalDebits: string;
  transactions: Transaction[];
  reportingCurrency: string;
}

/**
 * Generates a valid PDF 1.4 document containing the official ANDES ONE statement.
 * Conforms to the standard PDF specification so it opens in Acrobat, Chrome, macOS Preview, etc.
 */
export function generateStatementPdf(data: StatementData): Blob {
  const sanitize = (text: string) => text.replace(/[\\()]/g, '');

  let contentStream = '';
  // Initial page settings (letter 612 x 792 pts)
  // Header: ANDES GLOBAL / ANDES ONE
  contentStream += `BT /F2 20 Tf 50 740 Td (ANDES ONE - PRIVATE BANKING) Tj ET\n`;
  contentStream += `BT /F1 9 Tf 50 726 Td (A product of ANDES GLOBAL | Official Account Statement) Tj ET\n`;
  contentStream += `BT /F1 9 Tf 400 740 Td (Statement Period: ${sanitize(data.monthName)} ${data.year}) Tj ET\n`;
  contentStream += `BT /F1 9 Tf 400 726 Td (Account: ${sanitize(data.accountNumber)}) Tj ET\n`;

  // Horizontal dividing line
  contentStream += `0.5 w 50 710 m 562 710 l S\n`;

  // Client Details Box
  contentStream += `BT /F2 11 Tf 50 690 Td (Account Holder: ${sanitize(data.clientName)}) Tj ET\n`;
  contentStream += `BT /F1 9 Tf 50 676 Td (Tier 1 Prime Private Client | Currency: ${sanitize(data.reportingCurrency)}) Tj ET\n`;
  contentStream += `BT /F1 9 Tf 50 662 Td (Clearing: Andes Global Reserve Network & SWIFT Multi-Currency) Tj ET\n`;

  // Financial Summary
  contentStream += `0.5 w 50 645 m 562 645 l S\n`;
  contentStream += `BT /F2 10 Tf 50 630 Td (Opening Balance: ${sanitize(data.openingBalance)}) Tj ET\n`;
  contentStream += `BT /F2 10 Tf 190 630 Td (Credits: ${sanitize(data.totalCredits)}) Tj ET\n`;
  contentStream += `BT /F2 10 Tf 320 630 Td (Debits: ${sanitize(data.totalDebits)}) Tj ET\n`;
  contentStream += `BT /F2 10 Tf 440 630 Td (Closing: ${sanitize(data.closingBalance)}) Tj ET\n`;
  contentStream += `0.5 w 50 618 m 562 618 l S\n`;

  // Transactions Table Header
  contentStream += `BT /F2 9 Tf 50 600 Td (DATE) Tj ET\n`;
  contentStream += `BT /F2 9 Tf 110 600 Td (DESCRIPTION / COUNTERPARTY) Tj ET\n`;
  contentStream += `BT /F2 9 Tf 320 600 Td (CATEGORY) Tj ET\n`;
  contentStream += `BT /F2 9 Tf 420 600 Td (REFERENCE) Tj ET\n`;
  contentStream += `BT /F2 9 Tf 500 600 Td (AMOUNT) Tj ET\n`;
  contentStream += `0.3 w 50 592 m 562 592 l S\n`;

  // Transaction Rows
  let currentY = 575;
  const maxTx = Math.min(data.transactions.length, 18);

  for (let i = 0; i < maxTx; i++) {
    const tx = data.transactions[i];
    const sign = tx.type === 'debit' ? '-' : '+';
    const amountStr = `${sign}${tx.currency} ${tx.amount.toLocaleString('en-US', { minimumFractionDigits: 2 })}`;

    contentStream += `BT /F1 8 Tf 50 ${currentY} Td (${sanitize(tx.date)}) Tj ET\n`;
    contentStream += `BT /F2 8 Tf 110 ${currentY} Td (${sanitize(tx.description.slice(0, 32))}) Tj ET\n`;
    contentStream += `BT /F1 8 Tf 320 ${currentY} Td (${sanitize(tx.category)}) Tj ET\n`;
    contentStream += `BT /F1 7 Tf 420 ${currentY} Td (${sanitize(tx.reference.slice(0, 16))}) Tj ET\n`;
    contentStream += `BT /F2 8 Tf 500 ${currentY} Td (${sanitize(amountStr)}) Tj ET\n`;

    currentY -= 18;
    if (currentY < 120) break;
  }

  // Footer / Cryptographic Seal
  contentStream += `0.5 w 50 90 m 562 90 l S\n`;
  contentStream += `BT /F1 7 Tf 50 75 Td (CONFIDENTIAL - GENERATED BY ANDES ONE PROTOCOL. DEMONSTRATION RECORD.) Tj ET\n`;
  contentStream += `BT /F1 7 Tf 50 65 Td (SHA-256 DIGITAL LEDGER HASH: 9fa821c4091b72e819ac44b98129031ef84128a1) Tj ET\n`;
  contentStream += `BT /F2 7 Tf 400 75 Td (ANDES GLOBAL CLEARING LTD) Tj ET\n`;

  const streamLength = contentStream.length;

  const pdfParts = [
    `%PDF-1.4\n`,
    `1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n`,
    `2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n`,
    `3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>\nendobj\n`,
    `4 0 obj\n<< /Length ${streamLength} >>\nstream\n${contentStream}\nendstream\nendobj\n`,
    `5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n`,
    `6 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj\n`,
    `xref\n0 7\n0000000000 65535 f \n`,
    `trailer\n<< /Size 7 /Root 1 0 R >>\nstartxref\n%%EOF`,
  ];

  const fullPdf = pdfParts.join('');
  return new Blob([fullPdf], { type: 'application/pdf' });
}

/**
 * Triggers a download of the generated PDF file in the user's browser
 */
export function downloadStatementFile(data: StatementData) {
  const blob = generateStatementPdf(data);
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `ANDES_ONE_Statement_${data.monthName}_${data.year}.pdf`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
